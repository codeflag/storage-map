const KEY = 'sm-lang';
const index = (l) => (l === 'de' ? 1 : 0);

function initial() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'en' || saved === 'de') return saved;
  } catch { /* no storage, then the browser language decides */ }
  return (navigator.language || '').toLowerCase().startsWith('de') ? 'de' : 'en';
}

let current = initial();
document.documentElement.lang = current;

export const lang = () => current;

export function setLang(l) {
  current = l === 'de' ? 'de' : 'en';
  document.documentElement.lang = current;
  try { localStorage.setItem(KEY, current); } catch { /* stays for this window only */ }
}

/// Number and date formats follow the chosen language, in the variant of the browser if it matches.
export function locale() {
  const own = (navigator.languages || [navigator.language]).find((x) => x && x.toLowerCase().startsWith(current));
  return own || (current === 'de' ? 'de-DE' : 'en-US');
}

const fmtInt = (n) => new Intl.NumberFormat(locale(), { maximumFractionDigits: 0 }).format(n);
const fill = (s, vars) => (vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s);

function entry(key) {
  const e = TEXTS[key];
  if (!e) console.error(`Missing text: ${key}`);
  return e ? e[index(current)] : key;
}

/// The text for a key, with {name} placeholders filled in.
export function t(key, vars) {
  return fill(entry(key), vars);
}

/// A counted text: picks singular or plural and fills in {n}.
export function tn(key, n, vars) {
  const e = entry(key);
  const s = Array.isArray(e) ? e[n === 1 ? 0 : 1] : e;
  return fill(s, { n: fmtInt(n), ...vars });
}

/// Like t, but placeholders can be DOM nodes. Returns a list for h() or fill().
export function tp(key, nodes) {
  return entry(key).split(/(\{\w+\})/).map((part) => {
    const m = /^\{(\w+)\}$/.exec(part);
    return m && m[1] in nodes ? nodes[m[1]] : part;
  });
}

